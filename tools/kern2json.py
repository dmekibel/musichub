#!/usr/bin/env python3
"""Convert a **kern score into MusicHub's note list.

Usage: python3 tools/kern2json.py _src/wtc1p01.krn data/bwv846-notes.js BWV846_NOTES

Output is a plain list of facts about a public-domain work: onset and length
(in sixteenth notes), MIDI pitch, and the spelled note name. Tied notes are
merged into one note. The source .krn file stays in _src/ (gitignored); its
encoding belongs to CCARH, the music itself is public domain.
"""
import json, re, sys
from fractions import Fraction

STEP = {"c": 0, "d": 2, "e": 4, "f": 5, "g": 7, "a": 9, "b": 11}


def parse_note(tok):
    """Return (duration as Fraction of a whole note, midi or None, name, tie)."""
    m = re.search(r"(\d+)(\.*)", tok)        # tokens may start with a tie mark "["
    if not m:
        return None
    base = Fraction(1, int(m.group(1)))
    dur, add = base, base
    for _ in m.group(2):
        add /= 2
        dur += add
    if "r" in tok:
        return dur, None, None, None
    pm = re.search(r"([a-gA-G])\1*", tok)
    letters = pm.group(0)
    step = letters[0].lower()
    if letters[0].islower():
        octave = 3 + len(letters)          # c = C4, cc = C5
    else:
        octave = 4 - len(letters)          # C = C3, CC = C2
    acc = tok[pm.end():]
    sharps = len(re.match(r"^#*", acc).group(0))
    flats = len(re.match(r"^-*", acc).group(0))
    midi = 12 * (octave + 1) + STEP[step] + sharps - flats
    name = step.upper() + ("#" * sharps) + ("b" * flats) + str(octave)
    tie = "start" if "[" in tok else "end" if "]" in tok else "mid" if "_" in tok else None
    return dur, midi, name, tie


def convert(path):
    spines_t = [Fraction(0)]          # current time per spine (whole notes)
    bar = 0
    bar_start = {}
    raw = []                          # (onset, dur, midi, name, tie, spine_key)
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("!"):
            continue
        toks = line.split("\t")
        if line.startswith("**"):
            spines_t = [Fraction(0) for _ in toks]
            continue
        if toks[0].startswith("*"):
            new = []
            i = 0
            while i < len(toks):
                t = toks[i]
                if t == "*^":
                    new += [spines_t[i], spines_t[i]]
                elif t == "*v":
                    j = i
                    while j < len(toks) and toks[j] == "*v":
                        j += 1
                    new.append(max(spines_t[i:j]))
                    i = j
                    continue
                elif t == "*-":
                    pass
                else:
                    new.append(spines_t[i])
                i += 1
            spines_t = new
            continue
        if toks[0].startswith("="):
            m = re.match(r"^=(\d+)", toks[0])
            if m:
                bar = int(m.group(1))
                bar_start[bar] = max(spines_t)
            continue
        for s, tok in enumerate(toks):
            if tok == ".":
                continue
            onset = spines_t[s]
            longest = Fraction(0)
            for sub in tok.split(" "):     # chords are space-separated
                p = parse_note(sub)
                if not p:
                    continue
                dur, midi, name, tie = p
                longest = max(longest, dur)
                if midi is not None:
                    raw.append([onset, dur, midi, name, tie])
            spines_t[s] = onset + longest

    # merge ties: a tie end extends the open note of the same pitch
    notes, open_ties = [], {}
    for onset, dur, midi, name, tie in sorted(raw, key=lambda r: (r[0], r[2])):
        if tie in ("end", "mid") and midi in open_ties:
            n = open_ties[midi]
            n[1] += dur
            if tie == "end":
                del open_ties[midi]
            continue
        n = [onset, dur, midi, name]
        notes.append(n)
        if tie == "start":
            open_ties[midi] = n

    sixteenth = Fraction(1, 16)
    out = [[int(o / sixteenth), int(d / sixteenth), m, nm] for o, d, m, nm in notes]
    bars = [int(bar_start[b] / sixteenth) for b in sorted(bar_start)]
    return out, bars


if __name__ == "__main__":
    src, dst, var = sys.argv[1], sys.argv[2], sys.argv[3]
    notes, bars = convert(src)
    with open(dst, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/kern2json.py. Do not edit by hand.\n")
        f.write("// Each note: [onset, length, midi, name]; times in sixteenth notes.\n")
        f.write(f"export const {var} = {{\n  bars: {json.dumps(bars)},\n  notes: [\n")
        for n in notes:
            f.write("    " + json.dumps(n) + ",\n")
        f.write("  ],\n};\n")
    print(f"{len(notes)} notes, {len(bars)} bars -> {dst}")
